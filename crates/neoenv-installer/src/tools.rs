fn runtime_error(message: impl Into<String>) -> Diagnostic {
    Diagnostic::new(DiagnosticCategory::Runtime, "NEO520", message)
}

fn runtime_error_with_cause<E>(message: impl Into<String>, cause: E) -> Diagnostic
where
    E: std::error::Error + Send + Sync + 'static,
{
    runtime_error(message).with_cause(cause)
}

fn runtime_io(path: &Path, error: &io::Error) -> Diagnostic {
    runtime_error(format!("filesystem error at {}: {error}", path.display()))
        .with_cause(io::Error::new(error.kind(), error.to_string()))
}

fn file_error(path: &Path, error: &io::Error) -> Diagnostic {
    let category = if error.kind() == io::ErrorKind::NotFound {
        DiagnosticCategory::NotFound
    } else {
        DiagnosticCategory::Runtime
    };
    Diagnostic::new(
        category,
        "NEO511",
        format!("failed to read tool lockfile {}: {error}", path.display()),
    )
    .with_cause(io::Error::new(error.kind(), error.to_string()))
}

