/// The directories used by the verified provider installer.
///
/// Project installations retain the historical `.neoenv/{artifacts,tools}`
/// layout.  Global installations pass the `nenv` data directory itself and
/// deliberately use `{artifacts,tools}` below it; they must not accidentally
/// acquire a second project-style `.neoenv` component.
#[derive(Clone, Debug, Eq, PartialEq)]
// The `_directory` postfix is the clearest name for each field at the call
// sites that join them onto a storage root, so the shared postfix is kept.
#[allow(clippy::struct_field_names)]
pub struct ToolStorage {
    artifact_directory: PathBuf,
    install_directory: PathBuf,
    quarantine_directory: PathBuf,
}

impl ToolStorage {
    /// Returns storage rooted below a project directory.
    #[must_use]
    pub fn project(project_root: &Path) -> Self {
        Self {
            artifact_directory: project_root.join(ARTIFACT_DIRECTORY),
            install_directory: project_root.join(TOOL_DIRECTORY),
            quarantine_directory: project_root.join(neoenv_core::names::PROJECT_DIRECTORY),
        }
    }

    /// Returns storage rooted below a `nenv` global data directory.
    #[must_use]
    pub fn global(data_root: &Path) -> Self {
        Self {
            artifact_directory: data_root.join("artifacts"),
            install_directory: data_root.join("tools"),
            quarantine_directory: data_root.join(".global-install"),
        }
    }

    /// Returns the content-addressed artifact directory.
    #[must_use]
    pub fn artifact_directory(&self) -> &Path {
        &self.artifact_directory
    }

    /// Returns the content-addressed installation directory.
    #[must_use]
    pub fn install_directory(&self) -> &Path {
        &self.install_directory
    }

    /// Returns the private directory used while cleaning unreferenced entries.
    #[must_use]
    pub fn quarantine_directory(&self) -> &Path {
        &self.quarantine_directory
    }
}

/// Removes installer-owned temporary entries left by a terminated process.
///
/// Only names generated by this installer are considered.  On Unix a live
/// process ID protects an active installer; on other platforms an old entry is
/// removed only after a conservative grace period.
///
/// # Errors
///
/// Returns a diagnostic when a storage directory or stale entry cannot be
/// inspected or removed.
pub fn cleanup_stale_temporaries_in(storage: &ToolStorage) -> Result<(), Diagnostic> {
    for directory in [
        storage.artifact_directory(),
        storage.install_directory(),
        storage.quarantine_directory(),
    ] {
        cleanup_stale_temporary_directory(directory, 2)?;
    }
    Ok(())
}

fn cleanup_stale_temporary_directory(directory: &Path, depth: usize) -> Result<(), Diagnostic> {
    match fs::symlink_metadata(directory) {
        Ok(metadata) if metadata.file_type().is_dir() && !metadata.file_type().is_symlink() => {}
        Ok(_) => return Ok(()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(runtime_io(directory, &error)),
    }
    let entries = match fs::read_dir(directory) {
        Ok(entries) => entries,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(runtime_io(directory, &error)),
    };
    for entry in entries {
        let entry = entry.map_err(|error| runtime_io(directory, &error))?;
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let metadata = fs::symlink_metadata(&path).map_err(|error| runtime_io(&path, &error))?;
        if stale_installer_temporary(&name, &path) {
            if metadata.file_type().is_dir() && !metadata.file_type().is_symlink() {
                fs::remove_dir_all(&path).map_err(|error| runtime_io(&path, &error))?;
            } else if metadata.file_type().is_file() || metadata.file_type().is_symlink() {
                fs::remove_file(&path).map_err(|error| runtime_io(&path, &error))?;
            }
        } else if depth > 0
            && metadata.file_type().is_dir()
            && !metadata.file_type().is_symlink()
            && !neoenv_core::tools::is_sha256(&name)
            && !name.starts_with('.')
        {
            cleanup_stale_temporary_directory(&path, depth - 1)?;
        }
    }
    Ok(())
}

fn stale_installer_temporary(name: &str, path: &Path) -> bool {
    let cleanup_entry = name.starts_with(".cleanup.");
    if !name.starts_with('.')
        || (!cleanup_entry
            && !Path::new(name)
                .extension()
                .is_some_and(|extension| extension.eq_ignore_ascii_case("tmp")))
    {
        return false;
    }
    let parts = name.split('.').collect::<Vec<_>>();
    if parts.len() < 4
        || !matches!(
            parts[1],
            "artifact"
                | "install"
                | "go-download"
                | "go-install"
                | "node-download"
                | "node-install"
                | "zig-download"
                | "zig-install"
                | "deno-download"
                | "deno-install"
                | "uv-download"
                | "uv-install"
                | "rustup-bootstrap"
                | "rust-install"
                | "odin-download"
                | "odin-install"
                | "python-download"
                | "python-install"
                | "dotnet-download"
                | "dotnet-install"
                | "cleanup"
        )
    {
        return false;
    }
    let Some(pid) = parts[2].parse::<u32>().ok() else {
        return false;
    };
    if pid == std::process::id() {
        return false;
    }
    #[cfg(not(target_os = "linux"))]
    let _ = pid;
    #[cfg(target_os = "linux")]
    {
        let _ = path;
        !Path::new("/proc").join(pid.to_string()).exists()
    }
    #[cfg(not(target_os = "linux"))]
    {
        let Ok(metadata) = path.metadata() else {
            return false;
        };
        let Ok(modified) = metadata.modified() else {
            return false;
        };
        let Ok(age) = SystemTime::now().duration_since(modified) else {
            return false;
        };
        age.as_secs() >= 60
    }
}

