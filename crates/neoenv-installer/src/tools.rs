#[allow(clippy::needless_pass_by_value)] // The fallback is retained as the stable domain-facing error.
fn preserve_budget_error<E>(id: &str, error: E, fallback: ToolPlanError) -> ToolPlanError
where
    E: std::error::Error + Send + Sync + 'static,
{
    let message = error.to_string();
    let fallback = if message.contains("resource budget exceeded") {
        ToolPlanError::ResourceLimit {
            id: id.into(),
            message,
        }
    } else {
        fallback
    };
    ToolPlanError::ProviderSource {
        fallback: Box::new(fallback),
        source: Arc::new(error),
    }
}

