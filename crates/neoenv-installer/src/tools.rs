fn valid_binary_names(tool: &LockedTool) -> Result<(), Diagnostic> {
    if tool.binaries.iter().any(|binary| {
        let path = Path::new(binary);
        binary.is_empty()
            || path.is_absolute()
            || path.components().count() != 1
            || !matches!(path.components().next(), Some(Component::Normal(_)))
    }) {
        Err(runtime_error(format!(
            "tool {} has an unsafe binary name",
            tool.id
        )))
    } else {
        Ok(())
    }
}

fn verify_file(path: &Path, expected: &str) -> Result<bool, Diagnostic> {
    let input = fs::File::open(path).map_err(|error| runtime_io(path, &error))?;
    let mut reader = BudgetReader::new(
        input,
        ResourceLimit::Artifact,
        ResourceBudget::default().artifact_bytes,
    );
    let mut hasher = Sha256::new();
    io::copy(&mut reader, &mut HashWriter(&mut hasher))
        .map_err(|error| runtime_io(path, &error))?;
    Ok(format!("{:x}", hasher.finalize()) == expected)
}

struct HashWriter<'a>(&'a mut Sha256);
impl Write for HashWriter<'_> {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        self.0.update(bytes);
        Ok(bytes.len())
    }
    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

fn copy_and_verify(
    reader: &mut impl Read,
    output: &mut impl Write,
    expected: &str,
) -> Result<(), Diagnostic> {
    copy_and_verify_with_limit(
        reader,
        output,
        expected,
        ResourceBudget::default().artifact_bytes,
    )
}

fn copy_and_verify_with_limit(
    reader: &mut impl Read,
    output: &mut impl Write,
    expected: &str,
    limit: u64,
) -> Result<(), Diagnostic> {
    let mut reader = BudgetReader::new(reader, ResourceLimit::Artifact, limit);
    let mut hasher = Sha256::new();
    let mut buffer = [0_u8; 8192];
    loop {
        let read = reader
            .read(&mut buffer)
            .map_err(|error| runtime_error_with_cause(error.to_string(), error))?;
        if read == 0 {
            break;
        }
        hasher.update(&buffer[..read]);
        output
            .write_all(&buffer[..read])
            .map_err(|error| runtime_error_with_cause(error.to_string(), error))?;
    }
    let actual = format!("{:x}", hasher.finalize());
    if actual == expected {
        Ok(())
    } else {
        Err(runtime_error(format!(
            "SHA-256 mismatch: expected {expected}, got {actual}"
        )))
    }
}

fn temporary_path(parent: &Path, label: &str) -> Result<PathBuf, Diagnostic> {
    let time = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();
    loop {
        let path = parent.join(format!(
            ".{label}.{}.{}.tmp",
            std::process::id(),
            TEMP_SEQUENCE.fetch_add(1, Ordering::Relaxed) + time
        ));
        if !path.exists() {
            return Ok(path);
        }
    }
}

fn usable_file(path: &Path) -> bool {
    let Ok(metadata) = fs::symlink_metadata(path) else {
        return false;
    };
    if !metadata.file_type().is_file() {
        return false;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        metadata.permissions().mode() & 0o111 != 0
    }
    #[cfg(not(unix))]
    {
        true
    }
}

/// Marks a freshly written file executable.
///
/// **A no-op off Unix, and that is correct rather than a stub.** Windows has no
/// execute permission bit: what runs is decided by the file's extension and its
/// ACL, neither of which this call can influence. The sibling predicate
/// `usable_file` immediately above already answers `true` unconditionally on
/// `not(unix)` for the same reason, and a version of this function that carried a
/// `cfg(unix)` gate and nothing else did not compile on Windows at all: the
/// unconditional import in `archive.rs` failed with `E0432`, "unresolved import",
/// naming this function. Which is what the Windows runner exists to find, and it
/// had never run.
///
/// **This function is `cfg(unix)`, and the reason it was not for a while is the whole
/// point.** It used to be unconditional, with a no-op body for `not(unix)`, because an
/// unconditional import in `archive.rs` had failed with `E0432` when the function *was*
/// gated. That fixed the hard error and left two soft ones: all four call sites are
/// `#[cfg(unix)]`, so on Windows the function was defined and never called, and both the
/// import and the function warned. **A native Linux build cannot see either warning**,
/// which is how they survived a green gate -- so the repair gates the import and the
/// function together, at the same `cfg` as the callers, rather than widening the function.
///
/// The argument for a no-op body is sound, and it is kept where it applies: the sibling
/// predicate `usable_file` answers `true` unconditionally on `not(unix)` because Windows
/// has no execute permission bit, and it *is* called on every platform. It does not apply
/// here, because nothing calls this on Windows -- the four call sites are inside the
/// Unix-only extraction path, two of which write a `#!/bin/sh` launcher that Windows will
/// not execute regardless of any permission bit.
#[cfg(unix)]
fn make_executable(path: &Path) -> Result<(), Diagnostic> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(path, fs::Permissions::from_mode(0o755))
            .map_err(|error| runtime_io(path, &error))
    }
    #[cfg(not(unix))]
    {
        let _ = path;
        Ok(())
    }
}
